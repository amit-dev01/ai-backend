logger = logging.getLogger(__name__)


def _generate_fallback_pdf(title: str, text: str) -> bytes:
    """Minimal pure-bytes valid PDF 1.4 document when reportlab is not installed."""
    clean_title = title.replace("(", "").replace(")", "")[:60]
    clean_text = text.replace("(", "").replace(")", "")[:100]
    content = f"BT /F1 16 Tf 50 720 Td ({clean_title}) Tj ET BT /F1 11 Tf 50 680 Td ({clean_text}) Tj ET"
    stream_len = len(content.encode("latin-1", "replace"))
    return (
        b"%PDF-1.4\n"
        b"1 0 obj <</Type /Catalog /Pages 2 0 R>> endobj\n"
        b"2 0 obj <</Type /Pages /Kids [3 0 R] /Count 1>> endobj\n"
        b"3 0 obj <</Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources <</Font <</F1 5 0 R>>>>>> endobj\n"
        b"4 0 obj <</Length " + str(stream_len).encode() + b">> stream\n"
        + content.encode("latin-1", "replace") + b"\nendstream\nendobj\n"
        b"5 0 obj <</Type /Font /Subtype /Type1 /BaseFont /Helvetica>> endobj\n"
        b"xref\n0 6\n0000000000 65535 f \n0000000009 00000 n \n0000000058 00000 n \n0000000115 00000 n \n0000000244 00000 n \n0000000330 00000 n \n"
        b"trailer <</Size 6 /Root 1 0 R>>\nstartxref\n412\n%%EOF\n"
    )


class PDFReportService:
    """Generates institutional boardroom-ready competitive intelligence PDF documents."""

    @staticmethod
    def generate_boardroom_pdf(company_id: str) -> bytes:
        """
        Builds a comprehensive multi-page executive competitive intelligence PDF.
        """
        company = get_company_profile_by_id(company_id) or {}
        company_name = company.get("company_name", "Our Company")
        industry = company.get("industry", "Technology")
        weekly_brief = company.get("weekly_brief", "")

        if not REPORTLAB_AVAILABLE:
            logger.warning("ReportLab not available in environment. Returning fallback vector PDF.")
            return _generate_fallback_pdf(
                f"Competitive Intelligence Report: {company_name}",
                f"Generated by AI Competitive Intelligence Platform | {datetime.utcnow().strftime('%B %d, %Y')}"
            )

        # Gather multi-engine intelligence
        radar_data = PositioningEngine.get_positioning_radar(company_id)
        pricing_data = PricingMatrixService.get_category_pricing_matrix(company_id)
        deal_data = WinLossService.get_deal_analytics(company_id)
        sov_data = ShareOfVoiceService.get_category_share_of_voice(company_id)

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()

        # Premium Corporate Color Palette
        c_primary = colors.HexColor("#0F172A")    # Deep Navy Slate
        c_accent = colors.HexColor("#2563EB")     # Sapphire Blue
        c_alert = colors.HexColor("#DC2626")      # Critical Red
        c_success = colors.HexColor("#16A34A")    # Green
        c_light = colors.HexColor("#F8FAFC")      # Slate Light
        c_text = colors.HexColor("#334155")       # Charcoal

        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Title"],
            fontName="Helvetica-Bold",
            fontSize=20,
            leading=24,
            textColor=c_primary,
            alignment=0,
            spaceAfter=4
        )

        meta_style = ParagraphStyle(
            "DocMeta",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=13,
            textColor=c_accent,
            spaceAfter=10
        )

        h1_style = ParagraphStyle(
            "H1_Custom",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=13,
            leading=17,
            textColor=c_primary,
            spaceBefore=12,
            spaceAfter=6
        )

        body_style = ParagraphStyle(
            "Body_Custom",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8.5,
            leading=12,
            textColor=c_text,
            spaceAfter=6
        )

        bold_label = ParagraphStyle(
            "BoldLabel",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=8.5,
            leading=12,
            textColor=c_primary,
        )

        alert_style = ParagraphStyle(
            "AlertText",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=8.5,
            leading=12,
            textColor=c_alert,
        )

        elements = []

        # =============================================================
        # 1. HEADER & EXECUTIVE TITLE BLOCK
        # =============================================================
        elements.append(Paragraph("AURA-CI // EXECUTIVE COMPETITIVE DOSSIER", title_style))
        elements.append(Paragraph(
            f"Organization: <b>{company_name}</b> | Sector: <b>{industry}</b> | Date: <b>{datetime.utcnow().strftime('%B %d, %Y')}</b> | Classification: <b>CONFIDENTIAL / C-SUITE</b>",
            meta_style
        ))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=c_accent, spaceAfter=10))

        # =============================================================
        # 2. EXECUTIVE STRATEGY SUMMARY & DIRECTIVES
        # =============================================================
        elements.append(Paragraph("1. Executive Briefing & Strategic Imperative", h1_style))
        summary_narrative = weekly_brief or (
            f"Competitive dynamics in the {industry} sector are actively shifting. Competitors are adjusting entry-tier pricing "
            f"and accelerating AI-enabled features. Immediate strategic priority is consolidating market share across core product lines."
        )
        elements.append(Paragraph(f"<b>Executive Summary:</b> {summary_narrative}", body_style))

        # Strategic Priorities Table
        exec_priorities = [
            [
                Paragraph("<b>Strategic Pillar</b>", bold_label),
                Paragraph("<b>Market Observation</b>", bold_label),
                Paragraph("<b>Executive Mandate</b>", bold_label)
            ],
            [
                Paragraph("Pricing & Margins", body_style),
                Paragraph(f"Floor: ${pricing_data.get('categoryBenchmarks', {}).get('marketFloorMinima', 'N/A')}/mo | Ceiling: ${pricing_data.get('categoryBenchmarks', {}).get('marketCeilingMaxima', 'N/A')}/mo", body_style),
                Paragraph(pricing_data.get("strategicRecommendation", "Optimize entry pricing against competitor moves.")[:120], body_style)
            ],
            [
                Paragraph("Market Visibility", body_style),
                Paragraph(f"Category Buzz Leader: <b>{sov_data.get('categoryBuzzLeader', 'N/A')}</b> | Our Share of Voice: <b>{sov_data.get('ourShareOfVoice', 0)}%</b>", body_style),
                Paragraph("Accelerate high-impact comparison marketing and PR releases.", body_style)
            ],
            [
                Paragraph("Sales Execution", body_style),
                Paragraph(f"Win Rate: <b>{deal_data.get('overallWinRate', 0)}%</b> | Pipeline at Risk: <b>${deal_data.get('pipelineLost', 0):,.0f}</b>", body_style),
                Paragraph(deal_data.get("strategicRecommendation", "Arm reps with battlecards to exploit feature gaps.")[:120], body_style)
            ]
        ]
        t_exec = Table(exec_priorities, colWidths=[110, 190, 240])
        t_exec.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), c_light),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        elements.append(t_exec)
        elements.append(Spacer(1, 10))

        # =============================================================
        # 3. 2D SPATIAL POSITIONING RADAR & THREAT ENCROACHMENT
        # =============================================================
        elements.append(Paragraph("2. 2D Spatial Positioning Radar & Threat Encroachment", h1_style))
        home_node = radar_data.get("homeTeam", {})
        pos_summary = radar_data.get("strategicPositioningSummary", "Positioning analyzed across price and scope dimensions.")
        elements.append(Paragraph(f"<b>Spatial Assessment:</b> {pos_summary}", body_style))

        # Threat Distances Table
        threats = radar_data.get("threatDistances", [])
        threat_table_data = [
            [
                Paragraph("<b>Competitor</b>", bold_label),
                Paragraph("<b>Proximity Distance</b>", bold_label),
                Paragraph("<b>Severity</b>", bold_label),
                Paragraph("<b>Tactical Threat Assessment</b>", bold_label)
            ]
        ]
        for th in threats[:5]:
            dist = th.get("euclideanDistance", 50.0)
            sev = th.get("threatSeverity", "MODERATE")
            sev_p = Paragraph(sev, alert_style if "CRITICAL" in sev else bold_label)
            threat_table_data.append([
                Paragraph(th.get("name", "Rival"), body_style),
                Paragraph(f"{dist:.1f} pts", body_style),
                sev_p,
                Paragraph(th.get("strategicAlert", "")[:110], body_style)
            ])

        if len(threat_table_data) > 1:
            t_threat = Table(threat_table_data, colWidths=[110, 80, 110, 240])
            t_threat.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), c_light),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            elements.append(t_threat)
        elements.append(Spacer(1, 10))

        # =============================================================
        # 4. CATEGORY PRICING MATRIX & WHITESPACE BENCHMARKS
        # =============================================================
        elements.append(Paragraph("3. Category Pricing Matrix & Boundary Benchmarks", h1_style))
        comp_rows = pricing_data.get("competitorMatrix", [])
        pricing_table = [
            [
                Paragraph("<b>Rival Name</b>", bold_label),
                Paragraph("<b>Flagship Product</b>", bold_label),
                Paragraph("<b>Floor ($P_{min}$)</b>", bold_label),
                Paragraph("<b>Ceiling ($P_{max}$)</b>", bold_label),
                Paragraph("<b>Positioning Tier</b>", bold_label)
            ]
        ]
        for r in comp_rows[:7]:
            p_min = f"${r.get('priceMinima'):.0f}" if r.get('priceMinima') is not None else "Contact"
            p_max = f"${r.get('priceMaxima'):.0f}" if r.get('priceMaxima') is not None else "Contact"
            pricing_table.append([
                Paragraph(r.get("name", "")[:20], body_style),
                Paragraph(r.get("flagshipProduct", "")[:24], body_style),
                Paragraph(p_min, body_style),
                Paragraph(p_max, body_style),
                Paragraph(r.get("positioningTier", ""), body_style)
            ])

        if len(pricing_table) > 1:
            t_p = Table(pricing_table, colWidths=[110, 140, 80, 80, 130])
            t_p.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), c_light),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            elements.append(t_p)

        # Whitespace Opportunity Callout
        ws_list = pricing_data.get("macroWhitespaceGaps", [])
        if ws_list:
            ws = ws_list[0]
            elements.append(Spacer(1, 4))
            elements.append(Paragraph(
                f"<b>Identified Pricing Whitespace:</b> Unoccupied tier range between <b>${ws.get('unoccupiedTierRange', [0,0])[0]:.0f} and ${ws.get('unoccupiedTierRange', [0,0])[1]:.0f}/mo</b> (Gap Size: ${ws.get('gapSize', 0):.0f}). <i>{ws.get('opportunityRationale', '')}</i>",
                body_style
            ))
        elements.append(Spacer(1, 10))

        # =============================================================
        # 5. COMMERCIAL WIN/LOSS DEAL INTELLIGENCE
        # =============================================================
        elements.append(Paragraph("4. Commercial Win/Loss Deal Analytics", h1_style))
        h2h_rows = deal_data.get("headToHeadMatrix", [])
        deal_table = [
            [
                Paragraph("<b>Competitor</b>", bold_label),
                Paragraph("<b>Deals Analyzed</b>", bold_label),
                Paragraph("<b>Win Rate %</b>", bold_label),
                Paragraph("<b>Primary Root Cause of Loss</b>", bold_label)
            ]
        ]
        for d in h2h_rows[:5]:
            deal_table.append([
                Paragraph(d.get("competitorName", "Competitor"), body_style),
                Paragraph(str(d.get("totalDeals", 0)), body_style),
                Paragraph(f"{d.get('winRate', 0)}%", bold_label),
                Paragraph(d.get("primaryLossReason", "FEATURE_GAP"), body_style)
            ])

        if len(deal_table) > 1:
            t_d = Table(deal_table, colWidths=[140, 90, 80, 230])
            t_d.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), c_light),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            elements.append(t_d)
        elements.append(Spacer(1, 10))

        # =============================================================
        # 6. ACTION PLAYBOOK FOR DEPARTMENTS
        # =============================================================
        elements.append(Paragraph("5. Tactical Action Directives by Department", h1_style))
        elements.append(Paragraph("<b>Product Engineering:</b> Fast-track feature parity on integrations and audit compliance to eliminate competitor sales objections.", body_style))
        elements.append(Paragraph("<b>Sales & GTM:</b> Lay architectural landmines early in demo calls regarding competitor platform stability and hidden enterprise licensing.", body_style))
        elements.append(Paragraph("<b>Marketing & Growth:</b> Launch targeted comparison landing pages targeting competitor pricing changes and customer support friction.", body_style))

        # Build PDF document
        doc.build(elements)
        pdf_bytes = buffer.getvalue()
        buffer.close()

        logger.info("Generated detailed boardroom PDF for %s (%d bytes)", company_name, len(pdf_bytes))
        return pdf_bytes
